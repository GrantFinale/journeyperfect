/**
 * Static IATA → airport reference point lookup.
 *
 * Airport coordinates are stable for decades, so this is a build-time constant
 * rather than an API call or a database table. It exists so features that need
 * to measure a distance to an airport — most importantly "when do I have to
 * leave the house to make my flight" in the itinerary timeline — can work from
 * nothing but the IATA code the `Flight` model already stores.
 *
 * Coordinates are published airport reference points (the surveyed ARP that
 * appears in the ICAO/IATA and national AIP records for each field), rounded to
 * four decimal places — roughly 11 m, far below the precision that a driving
 * estimate needs. Time zones are IANA names.
 *
 * Coverage: every code referenced by `AIRPORT_MAPS` in `src/components/airport-info.tsx`,
 * the busy US domestic and regional fields a trip planner actually sees, and the
 * ~150 busiest airports worldwide.
 *
 * If an airport is missing, `getAirportCoords` returns `undefined` and callers
 * degrade gracefully (e.g. the timeline falls back to showing only the check-in
 * deadline). That is always preferable to a guessed coordinate: a wrong position
 * silently produces a wrong "leave by" time, which is worse than none at all.
 */

export interface AirportRecord {
  lat: number
  lng: number
  name: string
  city: string
  /** IANA time zone identifier. */
  tz: string
}

