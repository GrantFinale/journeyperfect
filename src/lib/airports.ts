/**
 * Look up an airport by IATA code. Case-insensitive, whitespace-tolerant.
 *
 * Returns `undefined` for unknown or malformed codes so callers can fall back
 * rather than act on a wrong position.
 */
export function getAirportCoords(iata: string | null | undefined): AirportRecord | undefined {
  if (!iata) return undefined
  const code = iata.trim().toUpperCase()
  if (code.length !== 3) return undefined
  return AIRPORT_COORDS[code]
}

/** Human-readable airport name for a code, falling back to the code itself. */
export function getAirportName(iata: string | null | undefined): string | null {
  const record = getAirportCoords(iata)
  if (record) return record.name
  return iata ? iata.trim().toUpperCase() : null
}

